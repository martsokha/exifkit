//! `cargo xtask codegen`: renders `src/tag/generated.rs` and `src/tag/enums.rs`.

use std::fmt::Write as _;
use std::io::Write as _;
use std::path::Path;
use std::process::{Command, Stdio};

use crate::table::{self, Count, Enum, Ifd, Namespace, Origin, Role, Table, Tag, Type};

const HEADER: &str = "@generated by `cargo xtask codegen` from `data/tags.toml`. Do not edit.";

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let source = std::fs::read_to_string(root.join("data/tags.toml"))
        .map_err(|e| format!("reading data/tags.toml: {e}"))?;
    let table = table::load(&source)?;

    let outputs = [
        ("src/tag/generated.rs", render_table(&table)),
        ("src/tag/enums.rs", render_enums(&table)),
    ];

    let mut stale = Vec::new();
    for (path, code) in outputs {
        let code = rustfmt(root, &code)?;
        let full = root.join(path);
        let current = std::fs::read_to_string(&full).unwrap_or_default();
        if current == code {
            continue;
        }
        if check {
            stale.push(path);
        } else {
            std::fs::write(&full, code).map_err(|e| format!("writing {path}: {e}"))?;
            println!("wrote {path}");
        }
    }

    let unverified: Vec<&str> = table
        .tags
        .iter()
        .filter(|t| !t.verified)
        .map(|t| t.name.as_str())
        .collect();
    if !unverified.is_empty() {
        eprintln!(
            "note: {} tag(s) still to verify against the CIPA spec: {}",
            unverified.len(),
            unverified.join(", ")
        );
    }

    if stale.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "out of date: {}. Run `cargo xtask codegen`.",
            stale.join(", ")
        ))
    }
}

/// Formats with the same rustfmt CI uses: nightly, because `rustfmt.toml` sets
/// unstable options. Set `RUSTFMT` to use a different binary.
fn rustfmt(root: &Path, code: &str) -> Result<String, String> {
    let mut command = match std::env::var_os("RUSTFMT") {
        Some(path) => Command::new(path),
        None => {
            let mut command = Command::new("rustfmt");
            command.arg("+nightly");
            command
        }
    };
    let mut child = command
        .args(["--edition", "2024", "--emit", "stdout", "--config-path"])
        .arg(root.join("rustfmt.toml"))
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::inherit())
        .spawn()
        .map_err(|e| format!("running rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("rustfmt: no stdin")?
        .write_all(code.as_bytes())
        .map_err(|e| format!("rustfmt: {e}"))?;
    let output = child
        .wait_with_output()
        .map_err(|e| format!("rustfmt: {e}"))?;
    if !output.status.success() {
        return Err(
            "rustfmt failed on generated code (is the nightly toolchain installed?)".into(),
        );
    }
    String::from_utf8(output.stdout).map_err(|e| format!("rustfmt: {e}"))
}

fn render_table(table: &Table) -> String {
    let mut out = String::new();
    let w = &mut out;
    line(w, "//! Tag constants and the static tag table.");
    line(w, "//!");
    line(w, &format!("//! {HEADER}"));
    line(w, "");
    line(w, "use crate::ifd::IfdKind;");
    line(
        w,
        "use crate::tag::{Count, Namespace, Origin, Role, Tag, TagInfo, Version};",
    );
    line(w, "use crate::tiff::Type;");
    line(w, "");

    line(w, "impl Tag {");
    for tag in &table.tags {
        let _ = writeln!(
            w,
            "/// `{}` (0x{:04X}), {}.",
            tag.name,
            tag.id,
            describe_ifd(tag.ifd())
        );
        let _ = writeln!(
            w,
            "pub const {}: Self = Self::new(Namespace::{}, 0x{:04X});",
            tag.const_name(),
            namespace(tag.ns),
            tag.id
        );
    }
    line(w, "}");
    line(w, "");

    line(w, "/// Every known tag, sorted by namespace and id.");
    line(w, "pub(super) static TAGS: &[TagInfo] = &[");
    for tag in &table.tags {
        render_info(w, tag);
    }
    line(w, "];");
    line(w, "");

    // Spec names and aliases, sorted, each with its index into TAGS.
    let mut names: Vec<(&str, usize)> = Vec::new();
    for (index, tag) in table.tags.iter().enumerate() {
        names.push((tag.name.as_str(), index));
        if let Some(alias) = &tag.alias {
            names.push((alias.as_str(), index));
        }
    }
    names.sort_unstable();
    line(
        w,
        "/// Spec names and ExifTool aliases, sorted, with indexes into [`TAGS`].",
    );
    line(w, "pub(super) static NAMES: &[(&str, u16)] = &[");
    for (name, index) in names {
        let _ = writeln!(w, "({name:?}, {index}),");
    }
    line(w, "];");
    out
}

fn render_info(w: &mut String, tag: &Tag) {
    let alias = tag
        .alias
        .as_ref()
        .map_or("None".to_owned(), |a| format!("Some({a:?})"));
    let types: Vec<String> = tag
        .types
        .iter()
        .map(|t| format!("Type::{}", ty(*t)))
        .collect();
    let count = match &tag.count {
        Count::Fixed(n) => format!("Count::Fixed({n})"),
        Count::Any(_) => "Count::Any".to_owned(),
        Count::OneOf(ns) => format!(
            "Count::OneOf(&[{}])",
            ns.iter().map(u32::to_string).collect::<Vec<_>>().join(", ")
        ),
    };
    let role = match tag.role {
        Role::Value => "Role::Value".to_owned(),
        Role::Pointer => format!(
            "Role::Pointer({})",
            ifd_kind(tag.target.unwrap_or(Ifd::SubIfd))
        ),
        Role::DataOffset => "Role::DataOffset".to_owned(),
        Role::DataLength => "Role::DataLength".to_owned(),
        Role::MakerNote => "Role::MakerNote".to_owned(),
        Role::Computed => "Role::Computed".to_owned(),
    };
    let since = match tag.since() {
        Ok(Some((major, minor))) => format!("Some(Version::new({major}, {minor}))"),
        _ => "None".to_owned(),
    };
    let values = tag
        .enum_name
        .as_ref()
        .map_or("&[]".to_owned(), |e| format!("super::{e}::VALUES"));

    let _ = writeln!(
        w,
        "TagInfo {{ tag: Tag::{}, name: {:?}, alias: {alias}, ifd: {}, types: &[{}], \
         count: {count}, role: {role}, origin: Origin::{}, since: {since}, personal: {}, \
         values: {values} }},",
        tag.const_name(),
        tag.name,
        ifd_kind(tag.ifd()),
        types.join(", "),
        origin(tag.origin),
        tag.personal,
    );
}

fn render_enums(table: &Table) -> String {
    let mut out = String::new();
    let w = &mut out;
    line(w, "//! Enumerated tag values.");
    line(w, "//!");
    line(w, &format!("//! {HEADER}"));
    line(w, "");
    line(w, "use core::fmt;");
    line(w, "");
    line(w, "use crate::set::IntoValue;");
    line(w, "use crate::tag::Tag;");
    line(w, "use crate::value::{FromValue, Value, ValueError};");
    for e in &table.enums {
        let users: Vec<&Tag> = table
            .tags
            .iter()
            .filter(|t| t.enum_name.as_deref() == Some(e.name.as_str()))
            .collect();
        render_enum(w, e, &users);
    }
    out
}

fn render_enum(w: &mut String, e: &Enum, users: &[&Tag]) {
    let links: Vec<String> = users
        .iter()
        .map(|t| format!("[`Tag::{0}`](crate::tag::Tag::{0})", t.const_name()))
        .collect();
    let name = &e.name;
    line(w, "");
    let _ = writeln!(w, "/// Values of {}.", links.join(", "));
    line(w, "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    line(w, "#[non_exhaustive]");
    let _ = writeln!(w, "pub enum {name} {{");
    for v in &e.values {
        let _ = writeln!(w, "/// {} ({}).", v.desc, v.value);
        let _ = writeln!(w, "{},", v.variant);
    }
    line(w, "/// A value the spec does not define.");
    line(w, "///");
    line(
        w,
        "/// Build it with [`Self::from_u16`] so defined values stay canonical.",
    );
    line(w, "Other(u16),");
    line(w, "}");
    line(w, "");

    let _ = writeln!(w, "impl {name} {{");
    line(w, "/// Defined values with their descriptions.");
    line(w, "pub const VALUES: &'static [(u16, &'static str)] = &[");
    for v in &e.values {
        let _ = writeln!(w, "({}, {:?}),", v.value, v.desc);
    }
    line(w, "];");
    line(w, "");
    line(
        w,
        "/// Converts a raw value. Undefined values become [`Self::Other`].",
    );
    line(w, "#[must_use]");
    line(w, "pub const fn from_u16(value: u16) -> Self {");
    line(w, "match value {");
    for v in &e.values {
        let _ = writeln!(w, "{} => Self::{},", v.value, v.variant);
    }
    line(w, "other => Self::Other(other),");
    line(w, "}");
    line(w, "}");
    line(w, "");
    line(w, "/// Returns the raw value.");
    line(w, "#[must_use]");
    line(w, "pub const fn to_u16(self) -> u16 {");
    line(w, "match self {");
    for v in &e.values {
        let _ = writeln!(w, "Self::{} => {},", v.variant, v.value);
    }
    line(w, "Self::Other(value) => value,");
    line(w, "}");
    line(w, "}");
    line(w, "");
    line(
        w,
        "/// Returns the description, or `None` for an undefined value.",
    );
    line(w, "#[must_use]");
    line(
        w,
        "pub const fn description(self) -> Option<&'static str> {",
    );
    line(w, "match self {");
    for v in &e.values {
        let _ = writeln!(w, "Self::{} => Some({:?}),", v.variant, v.desc);
    }
    line(w, "Self::Other(_) => None,");
    line(w, "}");
    line(w, "}");
    line(w, "}");
    line(w, "");

    let _ = writeln!(
        w,
        "impl From<u16> for {name} {{ fn from(value: u16) -> Self {{ Self::from_u16(value) }} }}"
    );
    line(w, "");
    let _ = writeln!(
        w,
        "impl From<{name}> for u16 {{ fn from(value: {name}) -> Self {{ value.to_u16() }} }}"
    );
    line(w, "");
    line(
        w,
        "/// Converts a single BYTE, SHORT, LONG or UNDEFINED value.",
    );
    let _ = writeln!(w, "impl FromValue for {name} {{");
    line(
        w,
        "fn from_value(value: &Value) -> Result<Self, ValueError> { u16::from_value(value).map(Self::from_u16) }",
    );
    line(w, "}");
    line(w, "");
    line(
        w,
        "/// Converts to the tag's integer type; [`Exif::set`](crate::Exif::set) checks the value is defined.",
    );
    let _ = writeln!(w, "impl IntoValue for {name} {{");
    line(
        w,
        "fn into_value(self, tag: Tag) -> Result<Value, ValueError> { self.to_u16().into_value(tag) }",
    );
    line(w, "}");
    line(w, "");
    let _ = writeln!(w, "impl fmt::Display for {name} {{");
    line(
        w,
        "fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {",
    );
    line(w, "match self.description() {");
    line(w, "Some(desc) => f.write_str(desc),");
    line(w, "None => write!(f, \"Unknown ({})\", self.to_u16()),");
    line(w, "}");
    line(w, "}");
    line(w, "}");
}

fn line(w: &mut String, s: &str) {
    w.push_str(s);
    w.push('\n');
}

fn namespace(ns: Namespace) -> &'static str {
    match ns {
        Namespace::Main => "Main",
        Namespace::Gps => "Gps",
        Namespace::Interop => "Interop",
    }
}

fn ifd_kind(ifd: Ifd) -> &'static str {
    match ifd {
        Ifd::Primary => "IfdKind::Primary",
        Ifd::Thumbnail => "IfdKind::Thumbnail",
        Ifd::Exif => "IfdKind::Exif",
        Ifd::Gps => "IfdKind::Gps",
        Ifd::Interop => "IfdKind::Interop",
        Ifd::SubIfd => "IfdKind::SubIfd(0)",
    }
}

fn describe_ifd(ifd: Ifd) -> &'static str {
    match ifd {
        Ifd::Primary => "in IFD0",
        Ifd::Thumbnail => "in IFD1",
        Ifd::Exif => "in the Exif IFD",
        Ifd::Gps => "in the GPS IFD",
        Ifd::Interop => "in the Interoperability IFD",
        Ifd::SubIfd => "in a SubIFD",
    }
}

fn ty(t: Type) -> &'static str {
    match t {
        Type::Byte => "Byte",
        Type::Ascii => "Ascii",
        Type::Short => "Short",
        Type::Long => "Long",
        Type::Rational => "Rational",
        Type::Sbyte => "SByte",
        Type::Undefined => "Undefined",
        Type::Sshort => "SShort",
        Type::Slong => "SLong",
        Type::Srational => "SRational",
        Type::Float => "Float",
        Type::Double => "Double",
        Type::Ifd => "Ifd",
        Type::Utf8 => "Utf8",
    }
}

fn origin(o: Origin) -> &'static str {
    match o {
        Origin::Tiff => "Tiff",
        Origin::TiffEp => "TiffEp",
        Origin::Exif => "Exif",
        Origin::Dng => "Dng",
        Origin::Adobe => "Adobe",
        Origin::Microsoft => "Microsoft",
        Origin::Other => "Other",
    }
}
